/* 取真实系列表条目（优先 baseId 精确表 SERIES_EXTRA，再按 kind 表 + 关键字过滤），不匹配返回 null → 通用命名 */
function seriesEntries(leaf, brand) {
  const exact = (SERIES_EXTRA[leaf.baseId] || SERIES_TABLES[leaf.baseId] || {})[brand];
  if (exact && exact.length) return exact;
  const table = (SERIES_TABLES[leaf.kind] || {})[brand];
  if (!table || !table.length) return null;
  const f = SERIES_BASE_FILTER[leaf.baseId];
  if (!f) return null;
  /* 短关键字（≤2 字符）要求系列名完全一致，防止 'M' 误伤 'Mavic' */
  const kept = table.filter((e) => f.some((kw) => (kw.length <= 2 ? e[0] === kw : e[0].indexOf(kw) !== -1)));
  return kept.length ? kept : null;
}

/* 由真实系列推算合理上市年份（数字序列按起始年递增，或按逐型号年份表），查不到返回 null */
